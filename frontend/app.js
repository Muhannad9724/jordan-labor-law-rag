// Applies translated text to every element carrying a data-i18n* marker, whether it's
// static markup from index.html or a node created later by this script (those set the
// same attributes at creation time -- see addQuestion/addAnswer/renderSources below).
// Scoped to `root` so a single new element can be translated on creation without
// re-walking the whole document.
function applyI18n(root = document) {
  const scope = root.querySelectorAll ? root : document;

  const withText = root.matches && root.matches("[data-i18n]") ? [root] : [];
  for (const el of [...withText, ...scope.querySelectorAll("[data-i18n]")]) {
    const key = el.getAttribute("data-i18n");
    let text = t(key);
    if (el.hasAttribute("data-i18n-count")) {
      text = text.replace("{n}", fmtNum(el.getAttribute("data-i18n-count")));
    }
    if (el.tagName === "TITLE") document.title = text;
    else el.textContent = text;
  }
  for (const el of scope.querySelectorAll("[data-i18n-placeholder]")) {
    el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
  }
  for (const el of scope.querySelectorAll("[data-i18n-aria]")) {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
  }
  for (const el of scope.querySelectorAll("[data-i18n-title]")) {
    el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
  }
}

// Switches the whole page's chrome -- headings, labels, buttons, placeholders, and the
// document direction -- between Arabic and English. Never touches conversation content
// already on screen: a question or answer is text the person actually asked/received,
// not UI chrome, and translating it would misrepresent what was said. Per-message
// direction is set independently per message (see isArabic() below), so it keeps
// rendering correctly regardless of which language the page chrome is in.
function setLanguage(lang) {
  uiLang = lang;
  localStorage.setItem("uiLang", lang);

  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";

  applyI18n(document);

  langToggleBtn.textContent = t("langToggleLabel");
  langToggleBtn.setAttribute("aria-label", t("langToggleAria"));
  langToggleBtn.setAttribute("title", t("langToggleAria"));

  // The opening screen and the empty sources rail are placeholders, not content --
  // re-render them fresh so their seed questions and heading pick up the new language.
  if (thread.querySelector(".opening")) renderOpening();
  if (railBody.querySelector(".rail-empty")) renderRailEmpty(t("railEmpty"));
  // Sources currently on display are real content (article text), but their chrome
  // (numerals, "Article N", law name, chip) is UI -- rebuild from the same data.
  if (lastRenderedSources) renderSources(lastRenderedSources);
}

