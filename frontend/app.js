function renderSources(sources) {
  lastRenderedSources = sources;
  railBody.innerHTML = "";
  railCount.textContent = fmtNum(sources.length);

  for (const s of sources) {
    const card = document.createElement("article");
    card.className = "article-card";

    const top = document.createElement("div");
    top.className = "card-top";

    const numeral = document.createElement("div");
    numeral.className = "card-numeral";
    numeral.textContent = fmtNum(s.article_number);
    top.appendChild(numeral);

    const meta = document.createElement("div");
    meta.className = "card-meta";

    const law = document.createElement("div");
    law.className = "card-law";
    law.textContent = LAW_NAMES[uiLang][s.law] || s.law;
    meta.appendChild(law);

    const label = document.createElement("div");
    label.className = "card-article-label";
    label.textContent = s.clause
      ? t("articleLabelClause").replace("{num}", fmtNum(s.article_number)).replace("{clause}", s.clause)
      : t("articleLabel").replace("{num}", fmtNum(s.article_number));
    meta.appendChild(label);

    top.appendChild(meta);

    const chip = document.createElement("span");
    chip.className = `lang-chip ${s.language}`;
    chip.textContent = s.language === "ar" ? t("langChipAr") : t("langChipEn");
    top.appendChild(chip);

    card.appendChild(top);

    const body = document.createElement("div");
    body.className = "card-text";
    body.dir = isArabic(s.text) ? "rtl" : "ltr";
    body.textContent = s.text;
    card.appendChild(body);

    const more = document.createElement("button");
    more.type = "button";
    more.className = "card-more";
    more.textContent = t("showFullText");
    more.addEventListener("click", () => {
      const open = body.classList.toggle("expanded");
      more.textContent = open ? t("collapseText") : t("showFullText");
    });
    card.appendChild(more);

    railBody.appendChild(card);
  }
  railBody.scrollTop = 0;
}

