// One SSE record is "event: NAME\ndata: JSON\n\n" -- see the matching writer,
// _sse() in src/api.py. Returns null for a record with no data line (SSE allows
// bare comments/keepalives; none are sent here, but a lenient parser costs nothing
// and a strict one would throw the entire stream away on one).
function parseSseEvent(raw) {
  let event = "message";
  const dataLines = [];
  for (const line of raw.split("\n")) {
    if (line.startsWith("event:")) event = line.slice(6).trim();
    else if (line.startsWith("data:")) dataLines.push(line.slice(5).trim());
  }
  if (!dataLines.length) return null;
  try {
    return { event, data: JSON.parse(dataLines.join("\n")) };
  } catch {
    return null;
  }
}

// Reads /ask/stream's response body as it arrives and calls onEvent() for each
// complete SSE record. Records are separated by a blank line ("\n\n"); a chunk from
// the network has no guaranteed relationship to record boundaries, so this buffers
// across reads rather than assuming one read = one event.
async function consumeSse(resp, onEvent) {
  const reader = resp.body.getReader();
  const decoder = new TextDecoder();
  let buffer = "";
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    buffer += decoder.decode(value, { stream: true });
    let idx;
    while ((idx = buffer.indexOf("\n\n")) !== -1) {
      const raw = buffer.slice(0, idx);
      buffer = buffer.slice(idx + 2);
      const evt = parseSseEvent(raw);
      if (evt) onEvent(evt);
    }
  }
}

// Renders growing answer text at most once per animation frame. Markdown gets
// re-parsed from scratch on every call (see updateAnswerBody) -- fine at these
// answer lengths, but there is no reason to do it on every single token when
// tokens can arrive faster than the screen repaints.
function throttledRenderer(entry) {
  let latestText = null;
  let scheduled = false;
  return (text) => {
    latestText = text;
    if (scheduled) return;
    scheduled = true;
    requestAnimationFrame(() => {
      scheduled = false;
      updateAnswerBody(entry, latestText);
    });
  };
}

// The in-flight request's controller, if any -- resetConversation() aborts it so
// starting a new conversation mid-answer doesn't leave a stale stream writing into
// a thread it no longer belongs to. Module-level because only one askQuestion()
// runs at a time (the composer and every suggestion chip are disabled while one is
// in flight), so there is never more than one to track.
let currentAbortController = null;

async function askQuestion(question) {
  const pending = addThinking();
  // Snapshot before this turn is recorded -- the server wants the conversation *prior*
  // to the current question, which it receives separately.
  const priorHistory = history.slice();

  const controller = new AbortController();
  currentAbortController = controller;

  let entry = null;          // set once the first token arrives
  let sources = null;
  let buffer = "";
  let render = null;
  let gotDoneEvent = false;

  try {
    const resp = await fetch(`${API_BASE_URL}/ask/stream`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ question, history: priorHistory }),
      signal: controller.signal,
    });

    if (!resp.ok) {
      pending.remove();
      const payload = await resp.json().catch(() => ({}));
      addFailure(typeof payload.detail === "string" ? payload.detail : t("genericError"));
      return;
    }

    await consumeSse(resp, (evt) => {
      if (evt.event === "sources") {
        // Sources depend only on retrieval, not on the model's wording, so there is
        // no reason to make them wait for the first answer token -- shown as soon
        // as they're known, same as they always were once the full answer arrived.
        sources = evt.data.sources || [];
        if (sources.length) renderSources(sources);
      } else if (evt.event === "token") {
        if (!entry) {
          pending.remove();               // replace "thinking..." with the real answer
          entry = beginAnswer(sources);
          render = throttledRenderer(entry);
        }
        buffer += evt.data.text;
        render(buffer);
      } else if (evt.event === "done") {
        gotDoneEvent = true;
        buffer = evt.data.answer ?? buffer;   // authoritative final text, incl. any
                                               // trailing part a dropped last frame missed
        if (!entry) {                    // model produced zero streamed tokens (rare)
          pending.remove();
          entry = beginAnswer(sources);
        }
        updateAnswerBody(entry, buffer);
      } else if (evt.event === "error") {
        throw new Error(evt.data.detail || "stream error");
      }
    });

    if (!gotDoneEvent) throw new Error("stream ended without completing");

    // Recorded only on success, and as a pair -- same rule the old JSON path used,
    // now checked against the SSE "done" event instead of a resolved fetch promise.
    recordTurn("user", question);
    recordTurn("assistant", buffer);

    // Not awaited: the answer is complete without it, and a slow or failed
    // suggestion call must not hold the composer disabled.
    fetchSuggestions(question, { answer: buffer, sources });
  } catch (err) {
    if (err.name === "AbortError") {
      // resetConversation() cancelled this on purpose -- #thread has already
      // been rebuilt fresh by the time this runs, so there is nothing here to
      // clean up or report; touching it would mean writing into someone else's
      // (the new conversation's) thread.
      return;
    }
    pending.remove();
    if (entry) {
      // Real text already reached the screen -- it stays. Wiping it out because
      // the connection died afterwards would be worse than leaving a genuine,
      // possibly-incomplete answer visible.
      console.warn("[ask/stream] ended early:", err);
    } else {
      addFailure(t("networkError"));
    }
  } finally {
    if (currentAbortController === controller) currentAbortController = null;
  }
}

async function fetchSuggestions(question, data) {
  if (!data.sources || !data.sources.length) return;
  try {
    const resp = await fetch(`${API_BASE_URL}/followups`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        question,
        answer: data.answer,
        chunk_ids: data.sources.map((s) => s.chunk_id),
      }),
    });
    if (!resp.ok) {                       // includes 429 -- silence is right for the user
      console.warn("[followups] HTTP", resp.status);
      return;
    }
    const payload = await resp.json();
    addSuggestions(payload.suggestions);
  } catch (err) {
    // Silent for the user, never for whoever has to debug it -- an empty catch here
    // swallowed rendering errors as indistinguishably as network ones.
    console.warn("[followups] failed:", err);
  }
}

function submitQuestion(question) {
  clearSuggestions();   // they belonged to the previous answer
  addQuestion(question);
  input.value = "";
  input.style.height = "auto";
  sendBtn.disabled = true;
  // reset-btn stays enabled through the request -- see resetConversation(),
  // which aborts an in-flight answer rather than needing to be blocked from
  // running while one is in progress.

  askQuestion(question).finally(() => {
    sendBtn.disabled = false;
    input.focus();
  });
}

composer.addEventListener("submit", (e) => {
  e.preventDefault();
  const question = input.value.trim();
  if (!question) return;
  submitQuestion(question);
});

// Still purely client-side: the server holds no session, so forgetting the conversation
// means clearing the history array this page sends with each request -- there is nothing
// to tell the backend. Since turns now carry over, this is the only way to start a
// genuinely fresh topic; without it a new question keeps getting rewritten against an
// unrelated earlier exchange.
//
// Works mid-answer: an in-flight askQuestion() is aborted first (see
// currentAbortController), which makes its fetch/stream reject and return without
// touching the DOM -- see askQuestion()'s AbortError branch. Without the abort,
// resetting mid-answer would clear #thread out from under that still-running
// request, and its pending .then() would go on to append the old answer into a
// thread that looks freshly reset, reading as a stale answer appearing from nowhere.
function resetConversation() {
  if (currentAbortController) {
    currentAbortController.abort();
    currentAbortController = null;
  }
  history = [];                  // the actual point of reset now that turns carry over
  clearSuggestions();
  renderOpening();               // also clears #thread
  renderRailEmpty(t("railEmpty"));
  document.body.classList.remove("reading");
  lastUserScrollAt = 0;
  input.value = "";
  input.style.height = "auto";
  sendBtn.disabled = false;      // in case a request was in flight and just got aborted
  window.scrollTo({ top: 0, behavior: reducedMotion ? "auto" : "smooth" });
  input.focus();
}

resetBtn.addEventListener("click", resetConversation);

input.addEventListener("keydown", (e) => {
  if (e.key === "Enter" && !e.shiftKey) {
    e.preventDefault();
    composer.requestSubmit();
  }
});

input.addEventListener("input", () => {
  input.style.height = "auto";
  input.style.height = `${Math.min(input.scrollHeight, 150)}px`;
  syncDockClearance();   // a grown textarea makes the dock taller
});

window.addEventListener("resize", syncDockClearance);
// iOS keeps window.innerHeight fixed when the on-screen keyboard opens (only the
// visible viewport shrinks), so "resize" alone never fires there -- Android
// typically fires both, so this is additive, not a replacement. Without it, the
// dock's last-measured height (and revealAnswer's room calculation, which reads
// window.innerHeight) can go stale exactly while the keyboard is up, which is the
// one moment mobile users interact with it most.
if (window.visualViewport) {
  window.visualViewport.addEventListener("resize", syncDockClearance);
}

